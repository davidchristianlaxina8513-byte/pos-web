-- Atomic sale: lock quota rows, reject overselling, and deduct exact recipe
-- requirements. Ingredient movements are retained for exact void reversal.
create or replace function public.process_sale(
  p_transaction_id uuid,
  p_payment_mode text,
  p_amount_received numeric,
  p_change_given numeric,
  p_items jsonb,
  p_date timestamptz
)
returns uuid language plpgsql security definer set search_path = public as $$
declare
  v_user_id uuid := auth.uid();
  v_role text := get_app_role();
  v_total numeric := 0;
  v_day date := business_date(p_date);
  v_order_no integer;
  v_item jsonb;
  v_product_id bigint;
  v_qty integer;
  v_price numeric;
  v_quota integer;
  v_sold integer;
  v_requirement record;
  v_on_hand numeric;
begin
  if v_role not in ('admin', 'cashier') then raise exception 'Not authenticated'; end if;
  if p_payment_mode not in ('cash', 'gcash', 'maya') then raise exception 'Unknown payment method'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'Cart is empty'; end if;
  if exists (select 1 from transactions where id = p_transaction_id) then return p_transaction_id; end if;
  perform ensure_daily_product_quotas(v_day);
  insert into order_number_counter(day, last) values (v_day, 0) on conflict (day) do nothing;
  update order_number_counter set last = last + 1 where day = v_day returning last into v_order_no;
  insert into transactions(id, user_id, total_amount, payment_mode, date, status,
    amount_received, change_given, order_number)
  values (p_transaction_id, v_user_id, 0, p_payment_mode, p_date, 'completed',
    p_amount_received, p_change_given, v_order_no);

  for v_item in select value from jsonb_array_elements(p_items) loop
    v_product_id := (v_item->>'product_id')::bigint;
    v_qty := (v_item->>'quantity')::integer;
    if v_qty <= 0 then raise exception 'Quantity must be greater than zero'; end if;
    select price into v_price from product where product_id = v_product_id and is_available;
    if v_price is null then raise exception 'Product % not found or unavailable', v_product_id; end if;
    select daily_quota into v_quota from daily_product_quotas
      where product_id = v_product_id and business_date = v_day for update;
    select coalesce(sum(ti.quantity), 0)::integer into v_sold
      from transaction_items ti join transactions t on t.id = ti.transaction_id
      where ti.product_id = v_product_id and t.status = 'completed' and business_date(t.date) = v_day;
    if v_sold + v_qty > v_quota then raise exception 'Daily quota reached for product %', v_product_id; end if;
    insert into transaction_items(id, transaction_id, product_id, quantity, subtotal)
      values (gen_random_uuid(), p_transaction_id, v_product_id, v_qty, v_price * v_qty);
    v_total := v_total + v_price * v_qty;
  end loop;

  for v_requirement in
    select pr.ingredient_id, sum(pr.quantity * (item->>'quantity')::integer) as required
    from jsonb_array_elements(p_items) item
    join product_recipe pr on pr.product_id = (item->>'product_id')::bigint
    group by pr.ingredient_id order by pr.ingredient_id
  loop
    select quantity into v_on_hand from ingredient_inventory
      where ingredient_id = v_requirement.ingredient_id for update;
    if v_on_hand is null or v_on_hand < v_requirement.required then
      raise exception 'Insufficient ingredient stock for ingredient %', v_requirement.ingredient_id;
    end if;
    update ingredient_inventory set quantity = quantity - v_requirement.required,
      updated_at = now() where ingredient_id = v_requirement.ingredient_id;
    insert into ingredient_movements(ingredient_id, movement_type, quantity,
      transaction_id, actor_id, occurred_at)
    values (v_requirement.ingredient_id, 'sale', v_requirement.required,
      p_transaction_id, v_user_id, p_date);
  end loop;
  update transactions set total_amount = v_total where id = p_transaction_id;
  insert into audit_log(event_type, entity_type, entity_id, actor_id, actor_role, details)
    values ('product_sold', 'transaction', p_transaction_id::text, v_user_id, v_role,
      jsonb_build_object('business_date', v_day, 'total', v_total));
  return p_transaction_id;
end;
$$;

