create or replace function public.ensure_daily_product_quotas(
  p_business_date date default public.business_date()
)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_role text := get_app_role();
begin
  if v_role not in ('admin', 'cashier') then raise exception 'Not authorized'; end if;

  with inserted as (
    insert into daily_product_quotas
      (product_id, business_date, initial_quota, daily_quota, created_by, updated_by)
    select product_id, p_business_date, default_daily_quota, default_daily_quota,
           auth.uid(), auth.uid()
    from product where is_available
    on conflict (product_id, business_date) do nothing
    returning product_id, daily_quota
  )
  insert into audit_log(event_type, entity_type, entity_id, actor_id, actor_role, details)
  select 'daily_quota_created', 'product', product_id::text, auth.uid(), v_role,
         jsonb_build_object('business_date', p_business_date, 'quota', daily_quota)
  from inserted;
end;
$$;

revoke all on function public.ensure_daily_product_quotas(date) from public;
grant execute on function public.ensure_daily_product_quotas(date) to authenticated;

create or replace function public.get_today_product_quotas()
returns table (
  product_id bigint,
  product_name text,
  default_quota integer,
  daily_quota integer,
  sold_quantity integer,
  remaining_quantity integer
)
language plpgsql security definer set search_path = public as $$
declare v_day date := business_date();
begin
  if get_app_role() not in ('admin', 'cashier') then raise exception 'Not authorized'; end if;
  perform ensure_daily_product_quotas(v_day);
  return query
    select p.product_id, p.name, p.default_daily_quota, q.daily_quota,
      coalesce(s.sold, 0)::integer,
      greatest(q.daily_quota - coalesce(s.sold, 0), 0)::integer
    from product p
    join daily_product_quotas q on q.product_id = p.product_id and q.business_date = v_day
    left join (
      select ti.product_id, sum(ti.quantity)::integer sold
      from transaction_items ti join transactions t on t.id = ti.transaction_id
      where t.status = 'completed' and business_date(t.date) = v_day
      group by ti.product_id
    ) s on s.product_id = p.product_id
    where p.is_available
    order by p.name;
end;
$$;

revoke all on function public.get_today_product_quotas() from public;
grant execute on function public.get_today_product_quotas() to authenticated;

create or replace function public.set_today_product_quota(
  p_product_id bigint,
  p_new_quota integer,
  p_reason text default null
)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_role text := get_app_role();
  v_day date := business_date();
  v_old integer;
  v_sold integer;
begin
  if v_role not in ('admin', 'cashier') then raise exception 'Not authorized'; end if;
  if p_new_quota < 0 then raise exception 'Daily quota cannot be negative'; end if;
  perform ensure_daily_product_quotas(v_day);
  select daily_quota into v_old from daily_product_quotas
    where product_id = p_product_id and business_date = v_day for update;
  if v_old is null then raise exception 'Product quota not found'; end if;
  select coalesce(sum(ti.quantity), 0)::integer into v_sold
    from transaction_items ti join transactions t on t.id = ti.transaction_id
    where ti.product_id = p_product_id and t.status = 'completed'
      and business_date(t.date) = v_day;
  if p_new_quota < v_sold then
    raise exception 'Daily quota cannot be lower than the quantity already sold. Minimum valid quota: %', v_sold;
  end if;
  if p_new_quota = v_old then return; end if;
  update daily_product_quotas set daily_quota = p_new_quota,
    updated_by = auth.uid(), updated_at = now()
    where product_id = p_product_id and business_date = v_day;
  insert into quota_changes(product_id, business_date, previous_quota, new_quota,
    changed_by, changed_by_role, reason)
  values (p_product_id, v_day, v_old, p_new_quota, auth.uid(), v_role, nullif(trim(p_reason), ''));
  insert into audit_log(event_type, entity_type, entity_id, actor_id, actor_role, details)
  values (case when p_new_quota > v_old then 'quota_increased' else 'quota_decreased' end,
    'daily_product_quota', p_product_id::text, auth.uid(), v_role,
    jsonb_build_object('business_date', v_day, 'old_quota', v_old,
      'new_quota', p_new_quota, 'reason', nullif(trim(p_reason), '')));
end;
$$;

revoke all on function public.set_today_product_quota(bigint, integer, text) from public;
grant execute on function public.set_today_product_quota(bigint, integer, text) to authenticated;

