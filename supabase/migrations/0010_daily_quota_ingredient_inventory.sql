-- 0010_daily_quota_ingredient_inventory.sql
-- Replace finished-product stock with ingredient inventory + daily quotas.
-- Legacy inventory/restock tables remain intact for historical records only.

alter table product add column if not exists default_daily_quota integer not null default 30;

do $$ begin
  alter table product add constraint product_default_daily_quota_nonnegative
    check (default_daily_quota >= 0);
exception when duplicate_object then null;
end $$;

create or replace function public.business_date(p_at timestamptz default now())
returns date language sql stable set search_path = public
as $$ select (p_at at time zone 'Asia/Manila')::date $$;

create table if not exists ingredient (
  ingredient_id bigint generated by default as identity primary key,
  name text not null unique,
  unit text not null check (unit in ('g', 'kg', 'ml', 'l', 'pcs', 'serving')),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists ingredient_inventory (
  ingredient_id bigint primary key references ingredient(ingredient_id) on delete restrict,
  quantity numeric(14,3) not null default 0 check (quantity >= 0),
  reorder_level numeric(14,3) not null default 0 check (reorder_level >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists product_recipe (
  product_id bigint not null references product(product_id) on delete cascade,
  ingredient_id bigint not null references ingredient(ingredient_id) on delete restrict,
  quantity numeric(14,3) not null check (quantity > 0),
  primary key (product_id, ingredient_id)
);

create table if not exists daily_product_quotas (
  product_id bigint not null references product(product_id) on delete cascade,
  business_date date not null,
