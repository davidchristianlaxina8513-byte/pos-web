create or replace function public.record_ingredient_stock_in(
  p_reference_number text,
  p_supplier text,
  p_received_at timestamptz,
  p_notes text,
  p_payment_method text,
  p_ewallet_reference text,
  p_evidence_path text,
  p_items jsonb
)
returns uuid language plpgsql security definer set search_path = public as $$
declare
  v_id uuid := gen_random_uuid();
  v_item jsonb;
  v_ingredient_id bigint;
  v_quantity numeric;
  v_unit text;
begin
  if get_app_role() <> 'admin' then raise exception 'Admin only'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'At least one ingredient is required';
  end if;
  insert into stock_in_receipts(stock_in_id, reference_number, supplier, received_at,
    recorded_by, notes, payment_method, ewallet_reference, evidence_path)
  values (v_id, nullif(trim(p_reference_number), ''), nullif(trim(p_supplier), ''),
    p_received_at, auth.uid(), nullif(trim(p_notes), ''), nullif(trim(p_payment_method), ''),
    nullif(trim(p_ewallet_reference), ''), nullif(trim(p_evidence_path), ''));
  for v_item in select value from jsonb_array_elements(p_items) loop
    v_ingredient_id := (v_item->>'ingredient_id')::bigint;
    v_quantity := (v_item->>'quantity')::numeric;
    if v_quantity <= 0 then raise exception 'Stock-in quantity must be greater than zero'; end if;
    select unit into v_unit from ingredient where ingredient_id = v_ingredient_id and is_active;
    if v_unit is null then raise exception 'Ingredient not found'; end if;
    insert into stock_in_items(stock_in_id, ingredient_id, quantity, unit)
      values (v_id, v_ingredient_id, v_quantity, v_unit);
    insert into ingredient_inventory(ingredient_id, quantity, reorder_level)
      values (v_ingredient_id, v_quantity, 0)
      on conflict (ingredient_id) do update set
        quantity = ingredient_inventory.quantity + excluded.quantity, updated_at = now();
    insert into ingredient_movements(ingredient_id, movement_type, quantity, stock_in_id, actor_id)
      values (v_ingredient_id, 'stock_in', v_quantity, v_id, auth.uid());
  end loop;
  insert into audit_log(event_type, entity_type, entity_id, actor_id, actor_role, details)
    values ('stock_in_created', 'stock_in_receipt', v_id::text, auth.uid(), 'admin',
      jsonb_build_object('reference_number', nullif(trim(p_reference_number), ''),
        'item_count', jsonb_array_length(p_items), 'has_evidence', p_evidence_path is not null));
  return v_id;
end;
$$;

