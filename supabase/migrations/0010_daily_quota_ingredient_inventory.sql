create or replace function public.void_sale(p_transaction_id uuid, p_reason text)
returns void language plpgsql security definer set search_path = public as $$
declare v_role text := get_app_role(); v_tx transactions%rowtype; v_move record;
begin
  if v_role not in ('admin', 'cashier') then raise exception 'Not authorized'; end if;
  if nullif(trim(p_reason), '') is null then raise exception 'Void reason is required'; end if;
  select * into v_tx from transactions where id = p_transaction_id for update;
  if v_tx.id is null then raise exception 'Transaction not found'; end if;
  if v_tx.status = 'voided' then raise exception 'Transaction already voided'; end if;
  if v_role <> 'admin' and v_tx.user_id <> auth.uid() then raise exception 'Not authorized to void this transaction'; end if;
  for v_move in select ingredient_id, quantity from ingredient_movements
    where transaction_id = p_transaction_id and movement_type = 'sale' order by ingredient_id
  loop
    update ingredient_inventory set quantity = quantity + v_move.quantity,
      updated_at = now() where ingredient_id = v_move.ingredient_id;
    insert into ingredient_movements(ingredient_id, movement_type, quantity,
      transaction_id, actor_id, note)
    values (v_move.ingredient_id, 'void', v_move.quantity, p_transaction_id,
      auth.uid(), 'Reversal of completed sale');
  end loop;
  update transactions set status = 'voided', void_reason = trim(p_reason),
    voided_by = auth.uid(), voided_at = now() where id = p_transaction_id;
  insert into audit_log(event_type, entity_type, entity_id, actor_id, actor_role, details)
    values ('product_sale_voided', 'transaction', p_transaction_id::text,
      auth.uid(), v_role, jsonb_build_object('reason', trim(p_reason), 'amount', v_tx.total_amount));
end;
$$;

revoke all on function public.void_sale(uuid, text) from public;
grant execute on function public.void_sale(uuid, text) to authenticated;

