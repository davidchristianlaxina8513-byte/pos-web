create or replace function public.check_reorder_level()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_open_id  bigint;
  v_supplier text;
begin
  if NEW.par_level is null then
    return NEW;
  end if;
  if NEW.quantity <= NEW.reorder_level then
    select request_id into v_open_id
      from reorder_requests
      where product_id = NEW.product_id and status in ('pending', 'ordered')
      for update;
    if v_open_id is not null then
      update reorder_requests
        set current_stock_snapshot = NEW.quantity,
            reorder_point_snapshot = NEW.reorder_level,
            par_level_snapshot = NEW.par_level,
            suggested_quantity = greatest(NEW.par_level - NEW.quantity, 0),
            updated_at = now()
        where request_id = v_open_id;
    else
      select supplier into v_supplier
        from stock_movements
        where stock_id = NEW.stock_id and supplier is not null
        order by date desc
        limit 1;
      insert into reorder_requests
        (product_id, current_stock_snapshot, reorder_point_snapshot,
         par_level_snapshot, suggested_quantity, status, supplier)
        values
        (NEW.product_id, NEW.quantity, NEW.reorder_level,
         NEW.par_level, greatest(NEW.par_level - NEW.quantity, 0),
         'pending', v_supplier);
    end if;
  else
    -- Recovered above the threshold: refresh snapshots, never auto-close.
    -- Closing (received/cancelled) is always a human decision.
    update reorder_requests
      set current_stock_snapshot = NEW.quantity,
          reorder_point_snapshot = NEW.reorder_level,
          par_level_snapshot = NEW.par_level,
          suggested_quantity = greatest(NEW.par_level - NEW.quantity, 0),
          updated_at = now()
      where product_id = NEW.product_id and status in ('pending', 'ordered');
  end if;
  return NEW;
end;
$$;

